#!/usr/bin/env python3
"""Builds main/zh_font.c from a Fusion Pixel Font 12px BDF (OFL-1.1, see main/ZH_FONT_LICENSE.md).

Only the glyphs the firmware really uses are kept: ASCII 0x20-0x7E plus every
non-ASCII character found in main/*.c. Usage:
    python3 tools/font/gen_zh_font.py fusion-pixel-12px-monospaced-zh_tw.bdf
"""
import glob, os, sys

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
bdf = sys.argv[1]

wanted = set(range(0x20, 0x7F))
for p in glob.glob(os.path.join(root, 'main', '*.c')):
    if p.endswith('zh_font.c'):
        continue
    for ch in open(p, encoding='utf-8').read():
        if ord(ch) > 0x7F:
            wanted.add(ord(ch))

glyphs, ascent = {}, 10
cur = None
for line in open(bdf, encoding='utf-8'):
    t = line.split()
    if not t:
        continue
    if t[0] == 'FONT_ASCENT':
        ascent = int(t[1])
    elif t[0] == 'STARTCHAR':
        cur = {'rows': []}
    elif cur is not None:
        if t[0] == 'ENCODING':
            cur['cp'] = int(t[1])
        elif t[0] == 'DWIDTH':
            cur['dw'] = int(t[1])
        elif t[0] == 'BBX':
            cur['bbx'] = tuple(int(x) for x in t[1:5])
        elif t[0] == 'BITMAP':
            cur['in_bitmap'] = True
        elif t[0] == 'ENDCHAR':
            if cur.get('cp') in wanted:
                glyphs[cur['cp']] = cur
            cur = None
        elif cur.get('in_bitmap'):
            cur['rows'].append((t[0], len(t[0]) * 4))

out, missing = [], []
for cp in sorted(wanted):
    g = glyphs.get(cp)
    if not g:
        missing.append(cp)
        continue
    w, h, xo, yo = g['bbx']
    cell_w = g['dw']
    rows = [0] * 12
    top = ascent - (yo + h)
    for i, (hexs, bits) in enumerate(g['rows']):
        v = int(hexs, 16)
        y = top + i
        if 0 <= y < 12:
            line = 0
            for b in range(w):                       # bit b from the left in the bitmap row
                if v & (1 << (bits - 1 - b)):
                    x = xo + b
                    if 0 <= x < cell_w:
                        line |= 1 << x               # bit x = column x from the left
            rows[y] = line
    out.append((cp, cell_w, rows))

if missing:
    print('missing glyphs:', ''.join(chr(c) for c in missing if c > 0x7F), [hex(c) for c in missing if c <= 0x7F])

with open(os.path.join(root, 'main', 'zh_font.c'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/font/gen_zh_font.py from Fusion Pixel Font 12px (OFL-1.1). Do not edit.\n')
    f.write('#include "zh_font.h"\n\nconst zh_glyph_t k_zh_glyphs[] = {\n')
    for cp, w, rows in out:
        f.write('    {0x%04X, %d, {%s}},\n' % (cp, w, ','.join('0x%03X' % r for r in rows)))
    f.write('};\nconst int k_zh_glyph_count = %d;\n' % len(out))
print('glyphs written:', len(out))
